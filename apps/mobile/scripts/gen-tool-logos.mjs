// Copies real AI brand logos (colour variants) from @lobehub/icons-static-png
// into assets/tool-logos and generates lib/tool-logos.ts (a require map keyed by
// the tool's display name, matching the web's tool registry).
//   node scripts/gen-tool-logos.mjs
import { existsSync, mkdirSync, copyFileSync, writeFileSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const mobileRoot = join(here, '..');
const pkgLight = join(mobileRoot, '..', '..', 'node_modules', '@lobehub', 'icons-static-png', 'light');
const outDir = join(mobileRoot, 'assets', 'tool-logos');

// display name → lobehub base slug (we prefer the "-color" file when present)
const MAP = {
  ChatGPT: 'openai',
  Claude: 'claude',
  Codex: 'codex',
  Gemini: 'gemini',
  Grok: 'grok',
  'Kling AI': 'kling',
  Midjourney: 'midjourney',
  Suno: 'suno',
  ElevenLabs: 'elevenlabs',
  Runway: 'runway',
  Perplexity: 'perplexity',
  'DALL·E': 'dalle',
  Kimi: 'kimi',
  Cursor: 'cursor',
  Windsurf: 'windsurf',
  Ollama: 'ollama',
  'Hugging Face': 'huggingface',
  OpenRouter: 'openrouter',
  'Google AI Studio': 'aistudio',
  Antigravity: 'antigravity',
  Lovable: 'lovable',
  Replit: 'replit',
  'Z.ai': 'zhipu',
  Prompt: 'openai',
  'AI Work': 'openai',
};

const available = existsSync(pkgLight) ? readdirSync(pkgLight) : [];
function pick(slug) {
  if (available.includes(`${slug}-color.png`)) return `${slug}-color.png`;
  if (available.includes(`${slug}.png`)) return `${slug}.png`;
  return null;
}

mkdirSync(outDir, { recursive: true });
const entries = [];
const copied = new Set();
for (const [name, slug] of Object.entries(MAP)) {
  const file = pick(slug);
  if (!file) continue;
  const dest = `${slug}.png`;
  if (!copied.has(dest)) {
    copyFileSync(join(pkgLight, file), join(outDir, dest));
    copied.add(dest);
  }
  entries.push({ name, dest });
}

const lines = entries.map((e) => `  ${JSON.stringify(e.name)}: require('../assets/tool-logos/${e.dest}'),`);
const out = `// AUTO-GENERATED by scripts/gen-tool-logos.mjs — do not edit by hand.
// Real AI brand logos (from @lobehub/icons-static-png), keyed by tool display name.
const LOGOS: Record<string, number> = {
${lines.join('\n')}
};

export function toolLogo(name: string | undefined | null): number | null {
  if (!name) return null;
  return LOGOS[name] ?? null;
}
`;
writeFileSync(join(mobileRoot, 'lib', 'tool-logos.ts'), out);
console.log(`Bundled ${copied.size} logos for ${entries.length} tools → lib/tool-logos.ts`);
