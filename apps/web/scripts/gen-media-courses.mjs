// ── generate JSON files + SQL ─────────────────────────────────────────────────
const COURSES = [suno, runway, midjourney]
const CONTENT_DIR = path.join(process.cwd(), "content", "lessons")

let sql = `-- Migration 018: seed media courses (Suno, Runway, Midjourney)
-- Generated by scripts/gen-media-courses.mjs — do not edit by hand.
-- These courses are path-only by default (show_in_daily=false): reached through
-- career paths (Music/Video/Image), not browsed in the Daily Learn grid.
-- Run AFTER migration 017 (adds show_in_daily). Safe to re-run.

`

const esc = (s) => s.replace(/'/g, "''")

for (const c of COURSES) {
  const dir = path.join(CONTENT_DIR, c.slug)
  fs.mkdirSync(dir, { recursive: true })
  const flat = c.units.flatMap((u) => u.lessons)
  const lessonCount = flat.length
  const unitCount = c.units.length

  // JSON lesson files
  flat.forEach((lesson, i) => {
    const steps = [...lesson.steps, { type: "done" }]
    const nn = String(i + 1).padStart(2, "0")
    fs.writeFileSync(path.join(dir, `${nn}.json`), JSON.stringify(steps, null, 2) + "\n")
  })

  // SQL: course row (path-only → show_in_daily=false), order_index after existing 12
  sql += `-- ═══ ${c.slug} ═══\n`
  sql += `insert into courses (slug, title, description, tool, level, status, units, lessons, order_index, show_in_daily)\n`
  sql += `values ('${c.slug}', '${esc(c.title)}', '${esc(c.description)}', '${c.tool}', '${c.level}', 'published', ${unitCount}, ${lessonCount}, 99, false)\n`
  sql += `on conflict (slug) do update set title=excluded.title, description=excluded.description, tool=excluded.tool, level=excluded.level, status='published', units=excluded.units, lessons=excluded.lessons, show_in_daily=false;\n\n`

  // units
  sql += `insert into course_units (course_id, title, order_index)\nselect c.id, v.title, v.ord from courses c, (values\n`
  sql += c.units.map((u, ui) => `  ('${esc(u.title)}', ${ui + 1})`).join(",\n")
  sql += `\n) as v(title, ord) where c.slug = '${c.slug}'\non conflict (course_id, order_index) do update set title = excluded.title;\n\n`

  // lessons
  sql += `insert into course_lessons (unit_id, title, kind, xp, order_index)\nselect u.id, v.title, v.kind, v.xp, v.ord\nfrom course_units u join courses c on c.id = u.course_id, (values\n`
  const rows = []
  c.units.forEach((u, ui) => {
    u.lessons.forEach((l, li) => {
      rows.push(`  (${ui + 1}, '${esc(l.title)}', '${l.kind}', ${l.xp}, ${li + 1})`)
    })
  })
  sql += rows.join(",\n")
  sql += `\n) as v(uord, title, kind, xp, ord)\nwhere c.slug = '${c.slug}' and u.order_index = v.uord\non conflict (unit_id, order_index) do update set title = excluded.title, kind = excluded.kind, xp = excluded.xp;\n\n`
}

fs.writeFileSync(path.join(process.cwd(), "supabase", "migrations", "018_media_courses.sql"), sql)

const totalLessons = COURSES.reduce((n, c) => n + c.units.flatMap((u) => u.lessons).length, 0)
console.log(`Wrote ${COURSES.length} courses, ${totalLessons} lesson JSON files + migration 018.`)
