const COURSES = [lovable, grok, elevenlabs, skills, mcp, advanced]
const CONTENT_DIR = path.join(process.cwd(), "content", "lessons")
const esc = (s) => s.replace(/'/g, "''")

let sql = `-- Migration 020: seed daily courses (Lovable, Grok) + Pro courses (AI Skills, MCP, Advanced AI)
-- Generated by scripts/gen-daily-pro-courses.mjs — do not edit by hand.
-- Lovable/Grok: free daily courses. The three ai-*-pro courses are Pro-only
-- (is_pro=true) — Free users see them with a Pro badge and are sent to /upgrade.
-- Run AFTER migrations 017 (show_in_daily) + 019 (is_pro). Safe to re-run.

`

let order = 13
for (const c of COURSES) {
  const dir = path.join(CONTENT_DIR, c.slug)
  fs.mkdirSync(dir, { recursive: true })
  const flat = c.units.flatMap((u) => u.lessons)
  flat.forEach((lesson, i) => {
    const steps = [...lesson.steps, { type: "done" }]
    fs.writeFileSync(path.join(dir, `${String(i + 1).padStart(2, "0")}.json`), JSON.stringify(steps, null, 2) + "\n")
  })

  sql += `-- ═══ ${c.slug} ═══\n`
  sql += `insert into courses (slug, title, description, tool, level, status, units, lessons, order_index, show_in_daily, is_pro)\n`
  sql += `values ('${c.slug}', '${esc(c.title)}', '${esc(c.description)}', '${c.tool}', '${c.level}', 'published', ${c.units.length}, ${flat.length}, ${order}, true, ${c.isPro})\n`
  sql += `on conflict (slug) do update set title=excluded.title, description=excluded.description, tool=excluded.tool, level=excluded.level, status='published', units=excluded.units, lessons=excluded.lessons, show_in_daily=true, is_pro=excluded.is_pro;\n\n`

  sql += `insert into course_units (course_id, title, order_index)\nselect c.id, v.title, v.ord from courses c, (values\n`
  sql += c.units.map((u, ui) => `  ('${esc(u.title)}', ${ui + 1})`).join(",\n")
  sql += `\n) as v(title, ord) where c.slug = '${c.slug}'\non conflict (course_id, order_index) do update set title = excluded.title;\n\n`

  sql += `insert into course_lessons (unit_id, title, kind, xp, order_index)\nselect u.id, v.title, v.kind, v.xp, v.ord\nfrom course_units u join courses c on c.id = u.course_id, (values\n`
  const rows = []
  c.units.forEach((u, ui) => u.lessons.forEach((l, li) => rows.push(`  (${ui + 1}, '${esc(l.title)}', '${l.kind}', ${l.xp}, ${li + 1})`)))
  sql += rows.join(",\n")
  sql += `\n) as v(uord, title, kind, xp, ord)\nwhere c.slug = '${c.slug}' and u.order_index = v.uord\non conflict (unit_id, order_index) do update set title = excluded.title, kind = excluded.kind, xp = excluded.xp;\n\n`
  order++
}

fs.writeFileSync(path.join(process.cwd(), "supabase", "migrations", "020_daily_pro_courses.sql"), sql)
const total = COURSES.reduce((n, c) => n + c.units.flatMap((u) => u.lessons).length, 0)
console.log(`Wrote ${COURSES.length} courses, ${total} lesson JSON files + migration 020.`)
